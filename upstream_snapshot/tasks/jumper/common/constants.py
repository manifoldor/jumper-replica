def get_spec(asset: Path | None = None) -> mujoco.MjSpec:
    """Compile the model. ``asset`` of None uses the default jumper.xml.

    Changing the model changes only the XML: the joint names, HOME pose and foot
    geom names below are still written against the default asset, so a
    structurally different model fails while the environment is being built rather
    than quietly producing wrong results.
    """
    path = Path(asset) if asset is not None else JUMPER_XML
    if not path.exists():
        hint = (
            "First run:\n"
            "  python assets/jumper/tools/build_jumper.py --src <source repository> "
            "--out assets/jumper/jumper.xml"
            if path == JUMPER_XML
            else "Check the path given to --model."
        )
        raise FileNotFoundError(f"{path} not found. {hint}")
    return mujoco.MjSpec.from_file(str(path))


