# kp=10 / kd=0.5, and the torque bounded by the servo's measured torque-speed
# curve rather than by a constant. armature and frictionloss come from the MJCF.
#
# **EFFORT_LIMIT was 2.0 and is now the measured plateau, 1.7464 N*m.** The old
# value had no recorded provenance -- it appeared here, in the MJCF's
# actuatorfrcrange and in the exported contract, and no file said whether it was
# a continuous rating, a peak, or a number inherited from the Isaac config. The
# hardware's plateau is 12.7% lower, so every previous run had a slightly
# stronger robot than exists. Standing does not notice: the six legs need at most
# 0.2296 N*m at HOME, 13.1% of the plateau (measured on the V1.6 model, see
# assets/jumper/motor/README.md).
#
# The name stays `EFFORT_LIMIT` because velocity_env.py and scripts/export.py
# both read it; what changed is that it is now a cap **on top of** the curve
# rather than the only bound.
#
# **It is a peak rating, holdable for 300 ms.** After that the actuator's
# thermal state derates the ceiling to `min(1.2 N*m, curve(speed))`; the two
# constraints cross at 40.19 rad/s, above which the curve was already the
# tighter of the two. So `EFFORT_LIMIT` is the *most* this robot can ever
# produce, not what it can produce for as long as it likes.
EFFORT_LIMIT = PLATEAU_TORQUE
STIFFNESS = 10.0
DAMPING = 0.5
ARMATURE = 0.0015

