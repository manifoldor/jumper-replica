# Action scale: the policy output is multiplied by it and added to the home pose
# to form the position target.
#
# **Do not use the formula mjlab applies to Go1**, `0.25 * effort / stiffness`.
# It holds for Go1's actuators (hip 0.373, knee 0.249 rad) but gives 0.044 rad
# here: this robot pairs kp=10 with a 1.7464 N*m plateau, so a position error of
# only 0.175 rad saturates the torque, and taking a quarter of that leaves 0.044.
# (The argument was first written against the old 2.0 N*m figure, where the
# numbers were 0.2 and 0.05; the real plateau makes the trap slightly worse.)
#
# Measured consequence: at 0.05 rad the policy **cannot lift a foot at all**. With
# a 0.16 m leg segment, raising the foot 0.03 m needs about 0.19 rad of joint
# rotation, which at scale=0.05 demands a 3.8-sigma action that a Gaussian policy
# essentially never samples. Trained for a full 3000 iterations with that value,
# vx/vy/wz tracking were all 0% and mean torque reached 2% of the limit -- the
# robot was not unwilling to walk, it had no usable action range.
#
# 0.25 is the value tuned on Isaac for **the same robot with the same PD gains**.
# It deliberately allows the policy to command position targets that saturate
# torque -- a position target is a setpoint, saturation during transients is
# expected, and that is normal in legged RL.
ACTION_SCALE = 0.25

JUMPER_ACTION_SCALE: dict[str, float] = {j: ACTION_SCALE for j in GAIT_JOINTS}

