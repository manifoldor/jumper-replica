"""Constants and the mjlab EntityCfg for the jumper hexapod.

A 22-DoF heterogeneous hexapod: two 5-DoF front arms (in FOOT mode the grippers
are locked and it walks on the rear jaw pads, `*F_palm_pad_b_link`) plus four 3-DoF
middle and rear legs.

The model is **Liuzu V1.6**, generated by `assets/jumper/tools/build_jumper.py` from
the CAD team's URDF export. Two geom sets coexist in one XML:

| Name | Contents |
|---|---|
| `<body>_visual`  | the link's mesh, display only |
| `<body>_meshcol` | the link's mesh, the collision geometry |

**There is one collision scheme: hybrid** -- foot meshes at source resolution plus
reduced geometry for every other link. It is what makes contact fidelity affordable
at scale: on the previous model, measured over 4096 environments, full meshes
everywhere cost 0.64 s per iteration and 61 GiB of `MjModel` copies, against 0.39 s
for the hybrid.

On V1.6 the reduced half is each link's convex hull, decimated to 64 sampled
directions -- the same density V1.5's source-provided collision meshes used.
See `_LINK_MESH`, which records why the exact hull was tried first and what it
cost.

The earlier all-`mesh` and all-`primitive` schemes have been deleted: the choice is
settled, and keeping them would give every config function a parameter that always
takes its default while tempting new experiments to rediscover a known trap.

Both geom sets stay in the XML. `CollisionCfg` with `disable_other_geoms=True`
zeroes contype/conaffinity on whatever is not selected, so nothing unselected takes
part in simulation -- and keeping dead geometry out of the file matters beyond
tidiness: at large environment counts the native backend strips visual meshes and
the live viewer then draws collision geometry, so anything left lying around
**makes the picture lie** about what is being simulated.

## What belongs in this file

**Facts about the hardware.** There is one chassis, one IMU, one set of current
sensors and one servo curve, so there is one value and four tasks read it:
`EFFORT_LIMIT` is the measured torque plateau, `STAND_Z` is how tall the robot
stands, `IMU_ANG_VEL_NOISE` is what a gyro bolted to a walking hexapod reads.

**Not tuning.** A weight, a reward target or a curriculum rung is a choice a gait
makes, and it belongs in that task's `env_cfg.py` even when all four agree --
`velocity_env_cfg` raises rather than defaulting for those. The test of which pile
a number belongs in is whether two gaits on this robot could reasonably want
different values: if yes it is the task's, if no it is here.

`docs/DESIGN.md` section 14 has the reasoning, and `tests/test_task_parity.py`
enforces the half of it that can be enforced.
"""

